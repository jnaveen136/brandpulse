"""Does the verifier catch hallucinated figures? A deterministic, offline evaluation.

    python -m llm.eval.verifier_eval          # writes reports/verifier_eval.json and .md

No LLM call is needed. The test answers are

  A. the offline assistant's answer to each of the 42 evaluation questions, with
     the tool results it was written from; and
  B. Gemini's 42 saved final answers (reports/llm_eval_runs/gemini.jsonl), with
     tool results regenerated by replaying the tool calls Gemini made (the tools
     are deterministic, so the results are what Gemini saw, apart from the
     review fixes to the KPI engine).

Three measurements, for the original verifier (llm/eval/baseline_verifier.py)
and the current one (llm/verifier.py):

  false alarms     share of genuine figures flagged as unsupported (lower is better)
  catch rate       one figure per answer is replaced by a plausible hallucination:
                   the true value nudged by ±1%, ±3%, ±10%, ±30%, or a lakh/crore
                   slip (×10). Share of those caught (higher is better). A nudge
                   that rounds back to the same text is skipped.
  random figures   share of random 1-decimal percentages accepted (lower is better)
"""
from __future__ import annotations

import json
import random
import re
import sys
from pathlib import Path

from llm import verifier as current
from llm.assistant import Assistant
from llm.config import Settings
from llm.eval import baseline_verifier as baseline
from llm.eval.questions import QUESTIONS

ROOT = Path(__file__).resolve().parents[2]
# Hand audit of the saved Gemini answers (each figure compared with the KPI engine's value).
# Both answers were marked "verified" and scored correct by the original evaluation.
KNOWN_WRONG = {
    # true values: Amazon ₹4.94 L (prev ₹3.90 L), BigBasket ₹4.53 L (prev ₹4.43 L): every figure 10x too big
    "Which retailer drives the most revenue for Dettol this year?": ["₹49.39 L", "₹38.96 L", "₹45.34 L", "₹44.34 L"],
    # true values: change ₹1.10 L, revenue ₹40.67 L, mix ₹0.63 L, volume ₹0.29 L, price ₹0.18 L,
    # Variant 2 ₹1.64 L: lakh/crore slips of 100x
    "Why did Dettol revenue fall this year?": ["₹1.10 Cr", "₹40.67 Cr", "₹63.4L", "₹29.1L", "₹17.9L", "₹164.1L"],
}
NUDGES = [("±1%", 0.01), ("±3%", 0.03), ("±10%", 0.10), ("±30%", 0.30), ("×10 slip", None)]


def _indian(n: int) -> str:
    s = str(n)
    if len(s) <= 3:
        return s
    head, tail = s[:-3], s[-3:]
    parts = []
    while len(head) > 2:
        parts.insert(0, head[-2:])
        head = head[:-2]
    return ",".join(([head] if head else []) + parts + [tail])


def render_like(raw: str, value: float) -> str:
    """Write `value` with the same decimals and digit grouping as the number text `raw`."""
    dec = len(raw.split(".")[1]) if "." in raw else 0
    s = f"{abs(value):.{dec}f}"
    if "," in raw:
        whole, _, frac = s.partition(".")
        indian = bool(re.search(r"\d,\d{2},", raw)) or bool(re.fullmatch(r"\d{1,2},\d{2},\d{3}.*", raw))
        whole = _indian(int(whole)) if indian else f"{int(whole):,}"
        s = whole + ("." + frac if frac else "")
    return s


def mutate(answer: str, fig, rng: random.Random, nudge) -> str | None:
    """Replace one figure's number in the answer by a hallucinated one."""
    m = re.search(r"\d{1,3}(?:,\d{2,3})+(?:\.\d+)?|\d+(?:\.\d+)?", fig.text)
    if not m or fig.text not in answer:
        return None
    raw = m.group(0)
    v = float(raw.replace(",", ""))
    if nudge is None:
        new = v * 10
    else:
        new = v * (1 + nudge * rng.choice([-1, 1]))
    txt = render_like(raw, new)
    if txt == raw:
        return None
    new_fig = fig.text[:m.start()] + txt + fig.text[m.end():]
    return answer.replace(fig.text, new_fig, 1)


def corpus(a: Assistant) -> list[dict]:
    items = []
    for q in QUESTIONS:
        name, args = a.offline.plan(q["q"], q["brand"], q["period"], q["mode"])
        if name == "_refuse":
            continue
        call = {k: v for k, v in args.items() if not k.startswith("_")}
        res = a.tools.run(name, call)
        items.append({"source": "offline", "q": q["q"], "answer": a.offline.answer(name, args, res), "results": [res]})
    store = ROOT / "reports" / "llm_eval_runs" / "gemini.jsonl"
    if store.exists():
        for line in store.read_text(encoding="utf-8").splitlines():
            r = json.loads(line)
            if not r["tool_calls"]:
                continue
            results = [a.tools.run(c["name"], c["args"]) for c in r["tool_calls"]]
            items.append({"source": "gemini", "q": r["q"], "answer": r["answer"], "results": results})
    return items


def evaluate(items: list[dict], entities: set[str], seed: int = 7) -> dict:
    out = {}
    for name, mod in (("baseline", baseline), ("current", current)):
        rng = random.Random(seed)
        check = mod.check if mod is baseline else (lambda a, r, q="": current.check(a, r, q, entities))
        genuine = flagged = 0
        caught = {k: [0, 0] for k, _ in NUDGES}
        rand_acc = rand_n = 0
        per_source = {}
        real_n = real_caught = 0
        for it in items:
            ok, bad = check(it["answer"], it["results"], it["q"])
            wrong = set(KNOWN_WRONG.get(it["q"], [])) if it["source"] == "gemini" else set()
            g = [f for f in ok + bad if f.text not in wrong]       # genuine (correct) figures
            fl = [f for f in bad if f.text not in wrong]           # correct figures rejected = false alarms
            real_n += len(wrong)
            real_caught += sum(f.text in wrong for f in bad)
            genuine += len(g)
            flagged += len(fl)
            ps = per_source.setdefault(it["source"], {"answers": 0, "figures": 0, "false_alarms": 0})
            ps["answers"] += 1
            ps["figures"] += len(g)
            ps["false_alarms"] += len(fl)
            figs = [f for f in ok if f.text in it["answer"] and f.text not in wrong]
            if figs:
                for label, nudge in NUDGES:
                    f = rng.choice(figs)
                    mutated = mutate(it["answer"], f, rng, nudge)
                    if mutated is None:
                        continue
                    _, bad_m = check(mutated, it["results"], it["q"])
                    caught[label][1] += 1
                    caught[label][0] += bool(bad_m)
            for _ in range(20):
                x = f"{rng.uniform(-30, 60):.1f}%"
                rand_n += 1
                rand_acc += not check(f"It changed by {x}.", it["results"], "")[1]
        tot_c = sum(c for c, _ in caught.values())
        tot_n = sum(n for _, n in caught.values())
        out[name] = {
            "answers": len(items), "genuine_figures": genuine, "false_alarms": flagged,
            "false_alarm_pct": 100 * flagged / max(genuine, 1),
            "catch_rate_pct": {k: (100 * c / n if n else None) for k, (c, n) in caught.items()},
            "catch_rate_overall_pct": 100 * tot_c / max(tot_n, 1), "mutations": tot_n,
            "random_pct_accepted_pct": 100 * rand_acc / max(rand_n, 1),
            "real_hallucinations": real_n, "real_hallucinations_caught": real_caught,
            "per_source": per_source,
        }
    return out


def main() -> None:
    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(errors="replace")
    a = Assistant(cfg=Settings("offline", None, (), None, None))
    items = corpus(a)
    res = evaluate(items, a.tools.entities)
    (ROOT / "reports" / "verifier_eval.json").write_text(json.dumps(res, indent=2), encoding="utf-8")
    b, c = res["baseline"], res["current"]
    lines = ["# Verifier evaluation: does it catch hallucinated figures?", "",
             f"{b['answers']} grounded answers ({b['per_source'].get('offline', {}).get('answers', 0)} offline, "
             f"{b['per_source'].get('gemini', {}).get('answers', 0)} Gemini), {b['genuine_figures']} genuine figures, "
             f"{c['mutations']} injected hallucinations. Deterministic (seed 7); run `python -m llm.eval.verifier_eval`.", "",
             "| Metric | Original verifier | Current verifier |", "|---|---|---|",
             f"| Real Gemini hallucinations caught (hand-audited, see below) | {b['real_hallucinations_caught']} of "
             f"{b['real_hallucinations']} | **{c['real_hallucinations_caught']} of {c['real_hallucinations']}** |",
             f"| Hallucinations caught (overall) | {b['catch_rate_overall_pct']:.0f}% | **{c['catch_rate_overall_pct']:.0f}%** |"]
    for k, _ in NUDGES:
        bv, cv = b["catch_rate_pct"][k], c["catch_rate_pct"][k]
        lines.append(f"| · true value {k} | {bv:.0f}% | {cv:.0f}% |")
    lines += [f"| Random 1-decimal % accepted | {b['random_pct_accepted_pct']:.0f}% | **{c['random_pct_accepted_pct']:.0f}%** |",
              f"| False alarms on genuine figures | {b['false_alarm_pct']:.1f}% | **{c['false_alarm_pct']:.1f}%** "
              f"({c['false_alarms']} of {c['genuine_figures']}) |", "",
              "Original = differences and % changes allowed between any two numbers in all tool results, no unit check. "
              "Current = only between numbers in the same tool object, ₹ figures never match % fields (or vice versa), and a "
              "figure in a sentence that names a brand / retailer / variant must come from that entity's tool object.", "",
              "## The real hallucinations", "",
              "Two saved Gemini answers were marked *verified* and scored *correct* by the original evaluation, "
              "but every rupee figure in them is a lakh/crore slip:", ""]
    lines += [f"- *{q}* → {', '.join(v)}" for q, v in KNOWN_WRONG.items()]
    lines += ["", "True values: Amazon ₹4.94 L and BigBasket ₹4.53 L (10× smaller); Dettol's YTD revenue is ₹40.67 **L**, "
              "the fall ₹1.10 L, mix ₹0.63 L, volume ₹0.29 L, discount ₹0.18 L, Variant 2 ₹1.64 L (100× smaller). "
              "The original verifier accepted them because, with thousands of pairwise differences to choose from, "
              "some unrelated difference matched each one.", "",
              "A figure that is still accepted after a nudge is one that happens to match another real number in the "
              "results at the written precision. The verifier proves a figure *exists* in the data, not that it is "
              "attached to the right entity; that residual risk is why the tools return compact, labelled results."]
    (ROOT / "reports" / "verifier_eval.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
